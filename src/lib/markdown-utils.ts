/**
 * Markdown 展示用文本规范化工具
 *
 * 对百宝箱偶尔产生的不规范格式进行最小兼容，
 * 不修改数据库中的原始消息。
 */

/**
 * 规范化 Markdown 文本中的轻微格式问题。
 *
 * 当前处理：
 * - "**直接结论： **" → "**直接结论：** "（加粗结束符号前的多余空格）
 *
 * 注意：只做精确的模式匹配，不做全局暴力替换，
 * 避免误伤代码块或正常星号。
 */
export function normalizeMarkdownContent(text: string): string {
  // 修正模式：**中文文本[：:] ** → **中文文本[：:]**
  // 匹配加粗标签内以中文冒号结尾、结束符号前有多余空格的情况
  return text.replace(/\*\*([^*]+?)[：:]\s+\*\*/g, "**$1：** ");
}
